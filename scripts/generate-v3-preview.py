def visit(name):
 if name in needed:return
 needed.add(name)
 def refs(node):
  if isinstance(node,dict):
   if '$ref' in node:visit(node['$ref'].split('/')[-1])
   for value in node.values():refs(value)
  elif isinstance(node,list):
   for value in node:refs(value)
 refs(engineering[name])
